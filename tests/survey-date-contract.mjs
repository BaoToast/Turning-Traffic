/*
 * ══════════════════════════════════════════════════════════════════════
 *  「同一份調查讀到幾個日期」：三支程式共用的判定契約
 * ══════════════════════════════════════════════════════════════════════
 *
 * ⚠️ **這個檔案在三支程式裡逐位元相同。** 改了其中一份就要三份一起改，
 *   否則同一份調查檔在三支會得到不同的日期候選——那比沒有這個功能更糟，
 *   因為使用者會以為是資料有問題。
 *   （與 `period-input-contract.mjs` 同一種做法。）
 *
 * 使用者 2026-09-20：
 *   「同一張表若你判讀到 2 個日期，在資料匯入時就應該做為異常顯示提醒使用者，
 *     在異常資料檢查結果也要檢查出來……因為有可能另一個不同的日期在該資料中
 *     有其意義存在，所以使用者不會修正資料」
 *
 * 呼叫端要提供：
 *   findAll(cells)  → FoundSurveyDate[]
 *   findOne(cells)  → FoundSurveyDate | null   （下游計算實際採用的那一個）
 */

const cell = (text, sheet = "平日", ref = "A1") => ({ text, sheet, cell: ref });

/**
 * 每一列：[標題, 儲存格清單, 期望的 iso 陣列, 這一列在防什麼]
 *
 * ⚠️ 期望值寫的是**順序**不只是集合：順序要與 findSurveyDate 的挑選規則一致，
 *   否則畫面上第一個候選會不是系統實際採用的那一個。
 */
export const SURVEY_DATE_CASES = [
  [
    "只有一個有標籤的日期",
    [cell("調查日期：115年05月04日(平日)", "平日", "F2")],
    ["2026-05-04"],
    "最常見的正常情況",
  ],
  [
    "同一天用兩種寫法 → 只算一個",
    [cell("調查日期：115年05月04日", "平日", "F2"), cell("115/05/04", "平日", "H2")],
    ["2026-05-04"],
    "⚠️ 依 iso 去重。列兩次會讓使用者以為有衝突",
  ],
  [
    "真的有兩個不同的日期",
    [cell("調查日期：115年05月04日", "平日", "F2"), cell("115/05/05", "平日", "H2")],
    ["2026-05-04", "2026-05-05"],
    "這就是要問使用者的那一種",
  ],
  [
    "有標籤的要排在沒標籤的前面",
    [cell("115/05/05", "平日", "H2"), cell("調查日期：115年05月04日", "平日", "F2")],
    ["2026-05-04", "2026-05-05"],
    "⚠️ 排序要與 findSurveyDate 的挑選規則一致",
  ],
  [
    "製表日期不算調查日期",
    [cell("調查日期：115年05月04日", "平日", "F2"), cell("製表日期：115年06月01日", "平日", "F3")],
    ["2026-05-04"],
    "⚠️ 非調查日期的標籤要排除，規則與 findSurveyDate 共用",
  ],
  [
    "複核日期也不算",
    [cell("調查日期：115年05月04日", "平日", "F2"), cell("複核日期：115年06月10日", "平日", "F4")],
    ["2026-05-04"],
    "同上",
  ],
  [
    "一個日期都沒有",
    [cell("路段：甲路(乙街～丙街)", "平日", "A1"), cell("單位：輛/hr", "平日", "A2")],
    [],
    "⚠️ 要回空陣列而不是丟例外——呼叫端靠長度判斷",
  ],
  [
    "空清單",
    [],
    [],
    "防呆",
  ],
  [
    "三個不同日期",
    [
      cell("調查日期：115年05月04日", "平日", "F2"),
      cell("115/05/05", "平日", "H2"),
      cell("115/05/06", "假日", "H2"),
    ],
    ["2026-05-04", "2026-05-05", "2026-05-06"],
    "兩個以上一樣要全部列出來",
  ],
];

export function checkSurveyDateContract(findAll, findOne, report) {
  /*
   * ⚠️ 前置檢查：案例表真的有內容，而且同時含有「只有一個」「有兩個」
   *   「一個都沒有」三種情形。少了這一條，案例表被清空時會安靜通過。
   */
  const sizes = new Set(SURVEY_DATE_CASES.map((row) => row[2].length));
  report(
    "前置：契約案例表有內容，而且涵蓋 0／1／多 三種情形",
    SURVEY_DATE_CASES.length >= 8 && sizes.has(0) && sizes.has(1) && sizes.size >= 3,
    `${SURVEY_DATE_CASES.length} 列，候選數量種類=${[...sizes].join("／")}`,
  );

  for (const [title, cells, expected, why] of SURVEY_DATE_CASES) {
    const actual = findAll(cells).map((x) => x.iso);
    report(
      title,
      JSON.stringify(actual) === JSON.stringify(expected),
      `期望 [${expected.join("、")}]，實際 [${actual.join("、")}]；這一列在防：${why}`,
    );
  }

  /*
   * ⚠️ 最重要的一條：**列出來的第一個，必須就是系統實際採用的那一個**。
   *   兩邊排序不同的話，畫面上請使用者確認的第一個候選，
   *   與計算實際用的那一個會是不同的日期——那比不問更糟。
   */
  for (const [title, cells] of SURVEY_DATE_CASES) {
    const all = findAll(cells);
    const one = findOne(cells);
    report(
      `${title}：列出來的第一個＝系統實際採用的那一個`,
      all.length === 0 ? one === null : one?.iso === all[0].iso,
      `findAll[0]=${all[0]?.iso ?? "(無)"}，findSurveyDate=${one?.iso ?? "(無)"}`,
    );
  }
}
