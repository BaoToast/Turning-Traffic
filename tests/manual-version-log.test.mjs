/*
 * 手冊裡不得出現「維護紀錄」。
 *
 * ── 使用者定的規則 ──
 *
 * 「手冊是要保留給新手看如何使用本程式的說明內容，一些維護過程、或不需要給
 *   使用者知道的訊息就不用放入手冊裡。畢竟身為使用者只須要知道當下功能的意義
 *   和如何使用就可以，程式曾經出了什麼問題，修復方法是什麼對使用者來說不重要，
 *   那是程式維護者才需要知道的事情。」
 *
 * 所以手冊只寫**現在的功能是什麼、怎麼用**。哪一版改了什麼、以前會怎樣、
 * 某個問題是怎麼修的——一律不寫。
 *
 * ── 為什麼需要守門 ──
 *
 * 手冊原本每升一版就往「版本變更」那一節再疊一則，從來沒有人清。
 * 累積到 2026-09-03 清理前，三支的狀況是：
 *   全日交通量  31 則，占整本手冊 52%（43 頁裡有一半以上不是教學）
 *   路口轉向    41 則，占整本超過一半
 *   交通服務水準 36 則，占整本約 35%
 * 使用者的原話是：「沒有新手會需要看這些改善紀錄。」
 *
 * 而那些也不是給維護者或 AI 看的——同一份歷史在 CHANGELOG、
 * 「【更新說明】請先讀我.txt」、各版 VALIDATION_*.md，以及（路口轉向）
 * lib/traffic.ts 的 VERSION_HISTORY 裡本來就有，手冊那份是第四份複本。
 * 重複的歷史正是先前 CHANGELOG 漏掉 21 個版本那一類問題的來源。
 *
 * 清理是一次性的，但**沒有守門就一定會長回去**——它本來就是這樣長起來的。
 *
 * ── 三次清理，三種漏法，所以有三支測試 ──
 *
 * 第一次：只掃 <div class="box"> 的 <span class="t"> 標題，漏掉包在同一個框裡、
 *   用 <strong>v2.1.13：…</strong> 當小標的四則，使用者翻到第 30 頁才發現。
 *   → 版本標題兩種樣式都要數（test 1）。
 * 第二次：把版本框刪光了，但章節標題還掛著「（本版新增）」。
 *   → 章節標題不得掛版本字樣（test 2）。
 * 第三次：版本框與版本標題都沒了，可是內文還在講故事——
 *   「舊版要輸入左右 X／上下 Y，現在改成拖曳」「v2.1.0 已修正」
 *   「過去這幾列顯示的是舊值…本版已修正」。標題乾淨，內容還是維護紀錄。
 *   → 內文不得出現維護敘事（test 3）。
 *
 * ── 加新功能說明時該怎麼寫 ──
 *
 * 寫「現在是什麼、怎麼用、為什麼要這樣用」，不要寫「以前是什麼、哪一版改的」。
 *   ✗ 舊版要填座標數字，v2.1.0 改成拖曳
 *   ✓ 圖卡與路口標籤直接用滑鼠拖曳定位
 * 版本歷史請寫進 CHANGELOG 與「【更新說明】請先讀我.txt」，那裡才是它們的家。
 *
 * ── 功能說明不要被誤刪 ──
 *
 * 清理時曾經把標題剛好帶版號、但內容其實是功能說明的區塊一起刪掉
 * （例如「v2.6 起的三個保護」講的是目前的匯入保護，不是某一版改了什麼）。
 * 那些已改寫成不帶版號的敘述，放在「附．補充說明」一節。
 * 之後要刪任何一則之前，請先確認它的內容在手冊他處還找得到。
 */
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const MANUAL = new URL("../scripts/manual/manual.html", import.meta.url);

/** 去標籤後的純文字，供內文掃描使用。 */
function plainText(manual) {
  return manual
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ");
}

/** 手冊裡所有「一則版本說明」的標題，兩種樣式都算。 */
function versionEntries(manual) {
  const hits = [];
  /* (a) 區塊標題：<div class="box …"><span class="t">…vX.Y… */
  for (const m of manual.matchAll(/<span class="t">([\s\S]*?)<\/span>/g))
    if (/v\d+(?:\.\d+)+/.test(m[1]))
      hits.push(m[1].replace(/<[^>]+>/g, "").trim());
  /* (b) 段落內的版本小標：<strong>vX.Y：…</strong>（第一次清理漏掉的就是這種） */
  for (const m of manual.matchAll(
    /<(?:strong|b|h3|h4)[^>]*>\s*(v\d+(?:\.\d+)+\s*[：:][^<]{0,80})/gi,
  ))
    hits.push(m[1].trim());
  return hits;
}

test("手冊裡不得有任何一則版本變更說明", () => {
  const manual = readFileSync(MANUAL, "utf8");
  const entries = versionEntries(manual);
  assert.deepEqual(
    entries.map((t) => t.slice(0, 60)),
    [],
    "手冊只寫「目前的功能與怎麼用」，不寫哪一版改了什麼。\n" +
      "版本紀錄請寫進 CHANGELOG.md 與「【更新說明】請先讀我.txt」。",
  );
});

test("章節標題不得掛版本字樣", () => {
  /*
   * 「時段車種分析（本版新增）」這種標題會跟著版本一起過期——那個功能是
   * 幾十版前加的，標題還寫「本版新增」只會誤導。清理時一併拿掉了 11 處。
   */
  const manual = readFileSync(MANUAL, "utf8");
  const bad = [...manual.matchAll(/<h2[^>]*>([\s\S]*?)<\/h2>/g)]
    .map((m) => m[1].replace(/<[^>]+>/g, "").trim())
    /*
      * ⚠️ 2026-09-25 補正（F6 第四輪抓到）：樣式要求 `起` 後面**緊接** `）`，
      *   而實際的寫法是「（v20.62 起，每一頁都看得到）」——`起` 後面是逗號，
      *   於是整條漏掉。三支手冊都有同一句，三支都沒被抓到。
      *   現在改成「括號裡出現版號」就算，不管後面接什麼。
      */
    .filter((t) =>
      /（本版新增）|本版變更|（[^）]*v\d+(?:\.\d+)+[^）]*）/.test(t),
    );
  assert.deepEqual(
    bad,
    [],
    "章節標題不可以掛「（本版新增）」「（vX 改版）」這類版本字樣：\n  " +
      bad.join("\n  "),
  );
});

test("內文不得出現維護敘事", () => {
  /*
   * 標題乾淨不代表內容乾淨。第三次清理抓到的就是這一種：
   *   「舊版要在這裡輸入『左右 X』『上下 Y』…現在改成拖曳」
   *   「v2.1.0 已修正：存檔次數從兩百多次降到 1 次」
   *   「過去這幾列顯示的是…的舊值…本版已修正」
   * 對使用者而言這些都是雜訊——他要知道的是現在怎麼操作。
   *
   * 這裡刻意只挑**明確在講版本沿革**的說法，避免誤傷正常用語：
   *   ・「保留舊版並建立新版」是匯入選項的名字
   *   ・「舊版 .xls」是 Excel 的檔案格式
   *   ・「遇到讀不進來的新版型」講的是報告版型
   * 所以「舊版／新版」不單獨入列，只有接在版本沿革語境裡的才算。
   */
  const text = plainText(readFileSync(MANUAL, "utf8"));
  const PATTERNS = [
    /本版(?:變更|已|新增|改成|把|修正)/g,
    /v\d+(?:\.\d+)+\s*(?:已修正|已取消|改成|起新增|新增了)/g,
    /*
     * ⚠️ 2026-09-25 補正（F6 第四輪抓到）：字元類原本是 `[^。]`，
     *   也就是**分號會把子句切斷**。實際踩到的寫法正是
     *     「以前這些條件散在各區塊、有些頁甚至沒有條件可設**；**（換行）現在集中在這裡」
     *   分號一擋，這一條就整段漏掉——三支手冊都有同一句，三支都沒被抓到。
     *   現在只排除句號，分號與換行都跨得過去。
     */
    /(?:舊版|過去|以前|之前|原本)[^。]{0,60}(?:(?<![出發浮呈])現在|本版|已改|已修正|改成)/g,
    /*
     * ⚠️ 2026-09-25 新增：「現在是／不再／改成」這一組**不含過去詞**，
     *   所以上面那一條抓不到。實際踩到的：
     *     「成果範圍**現在是**「一段期間」，**不再**限定單一季度」
     *     「畫面上**不再**列出」「**不再有**「兩天合計」的數字」
     *   這種寫法預設讀者知道舊行為，是典型的改版口吻。
     * ⚠️ 「不再」有正常用法（「**不再**需要的舊計畫」＝不需要了），
     *   所以只擋「不再」接在**功能敘述**上的那幾種，並排除「不再需要」。
     */
    /現在是[「『]/g,
    /不再(?!需要)(?:列出|有|限定|支援|提供|顯示|出現)/g,
    /(?:已修正|已修復|修正了一個|順帶修正|這一版修正)/g,
    /更新到\s*v\d+(?:\.\d+)+/g,
    /升版(?:時|之後|後)[^。]{0,20}(?:會|請)/g,
    /*
     * ⚠️ 2026-09-25 第五輪獨立複查補的兩條。上面那幾條都要求出現「本版」
     *   或一個版號，所以下面這兩種寫法全部漏掉（三支各抓到實例）：
     *     ・「圖旁邊的說明欄位是**這一版的重點**。」
     *     ・「**左側選單新增**〔結論草稿〕。」
     *   兩句都是維護敘事：前者會隨版本過期，後者在講「這一版多了什麼」。
     * ⚠️ 第二條刻意只認「選單／畫面／某一頁**新增**」這種主詞，
     *   不認單獨的「新增」——「按『＋ 新增支線』」是操作說明，不可以誤傷。
     */
    /(?:這一版|此版|本次改版)[^。]{0,25}(?:重點|新增|改成|已|會|修正)/g,
    /(?:左側選單|側欄|畫面上|這一頁|這一區|這一塊|工具列)(?:新增|多了|改成了)/g,
  ];
  const bad = [];
  for (const re of PATTERNS)
    for (const m of text.matchAll(re)) {
      const at = m.index ?? 0;
      bad.push(text.slice(Math.max(0, at - 30), at + m[0].length + 45).trim());
    }
  assert.deepEqual(
    bad,
    [],
    "手冊內文出現了維護敘事（程式以前怎樣、哪一版修的）。\n" +
      "請改寫成只描述目前的行為，例如\n" +
      "  ✗ 舊版要填座標數字，v2.1.0 改成拖曳\n" +
      "  ✓ 圖卡與路口標籤直接用滑鼠拖曳定位\n" +
      "命中的片段：\n  " +
      bad.join("\n  "),
  );
});
