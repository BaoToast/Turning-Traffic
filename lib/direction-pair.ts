/*
 * ══════════════════════════════════════════════════════════════════════
 *  方向名稱「成不成對」——三支程式共用的判斷
 * ══════════════════════════════════════════════════════════════════════
 *
 * 使用者 2026-09-20 指定：
 *   「成對有各種組合，其中『北』對應『南』，『東』對應『西』，
 *     不管方向後面 + 了什麼字（因為可能使用者不會使用北上/南下，
 *     而是北行/南行之類的名詞，所以關鍵字在於東西南北），
 *     如果出現不成對的話，請在異常檢查中檢查出來（匯入時也可以做異常提醒，
 *     但不阻擋匯入），由使用者手動去按確認（堅持是對的話），
 *     或自行修正資料後，重新匯入」
 *
 * ── 這一支與「方向對應不一致」是兩件不同的事，不可以混在一起 ──
 *
 *   「方向對應不一致」防的是：**調查員換了旅次起跑方向**——同一個「方向1」
 *   在某一季是 A→B、另一季變成 B→A，跨季比較就會拿相反方向互比。
 *   它看的是**原始報告上寫的旅次順序**。
 *
 *   這一支防的是：**使用者自己取的顯示名稱不成對**——「北上／西行」
 *   不是一條路的兩個方向，八成是其中一個打錯了。
 *   它看的是**顯示名稱**。
 *
 * ── ⚠️ 為什麼不是「字串裡有沒有出現東西南北」 ──
 *
 *   那會把地名整批誤判：**台北**、**南投**、**東港**、**西螺**、**北屯路**
 *   裡面都有方位字。「往台北／往高雄」是完全正常的命名，卻會被判成
 *   「北 對上 沒有方位」而報異常——使用者會學會忽略這個提醒，
 *   那比沒有這個檢查更糟。
 *
 *   所以改成：**整個名稱要長得像一個方位詞**才算數。
 *   `^(往)?(東北|西北|東南|西南|東|西|南|北)(上|下|行|向|往|進|側|端|線|方向)?$`
 *   ——「北上」「南下」「北行」「往東」「西」都算；
 *   「往台北」「北屯路」「南投」都**不算**（整串對不上）。
 *
 * ── ⚠️ 只有「兩邊都是方位詞」時才表示意見 ──
 *
 *   一邊是方位詞、另一邊不是（例如「北上／往竹科」），這一支**不表示意見**。
 *   那可能是使用者刻意的混合命名，而且無從判斷哪一邊才是對的。
 *   誤報一次，使用者就會開始忽略所有提醒。
 */

/** 單一方位與複合方位的對應表。⚠️ 要雙向都寫，查表才不必再做一次反查。 */
const OPPOSITE: Record<string, string> = {
  東: "西",
  西: "東",
  南: "北",
  北: "南",
  東北: "西南",
  西南: "東北",
  西北: "東南",
  東南: "西北",
};

/*
 * ⚠️ 複合方位（東北／西南…）一定要排在單一方位前面。
 *   正規表示式的交替是**由左往右取第一個match**，
 *   單一方位排前面的話「東北」會被切成「東」，於是「東北／西南」
 *   變成「東 對上 西」——剛好是相反的結論（誤判成成對）。
 */
const BEARING =
  /^(?:往)?(東北|西北|東南|西南|東|西|南|北)(?:上|下|行|向|往|進|側|端|線|方向)?$/;

/**
 * 從一個方向顯示名稱裡取出方位字；整串不像方位詞就回 `null`。
 *
 * ⚠️ 先做 NFKC 正規化並去掉全部空白與常見分隔符：
 *   真實資料裡出現過「北 上」「北－上」這種寫法，不處理的話會漏判。
 */
export function bearingOf(name: unknown): string | null {
  const text = String(name ?? "")
    .normalize("NFKC")
    .replace(/[\s　·．.、,，\-－—–_/／|]/g, "");
  if (!text) return null;
  const hit = BEARING.exec(text);
  return hit ? hit[1] : null;
}

export type DirectionPairVerdict =
  /** 兩邊都是方位詞，而且互為相反 → 成對。 */
  | { kind: "paired"; a: string; b: string }
  /** 兩邊都是方位詞，但不是相反 → 這是要報出來的那一種。 */
  | { kind: "mismatched"; a: string; b: string; expected: string }
  /** 至少一邊不像方位詞 → 這一支不表示意見（理由見檔頭）。 */
  | { kind: "not-applicable"; reason: string };

/**
 * 判斷兩個方向顯示名稱成不成對。
 *
 * ⚠️ 回傳的是**三態**不是布林值。用布林的話，「不表示意見」會被迫歸到
 *   true 或 false 其中一邊：歸 false 會把「往竹科／往台北」報成異常，
 *   歸 true 則讓呼叫端分不出「確認過成對」與「根本沒看」。
 */
export function judgeDirectionPair(
  nameA: unknown,
  nameB: unknown,
): DirectionPairVerdict {
  const a = bearingOf(nameA);
  const b = bearingOf(nameB);
  if (!a || !b)
    return {
      kind: "not-applicable",
      reason: !a && !b ? "兩個方向名稱都不是方位詞" : "只有一個方向名稱是方位詞",
    };
  if (OPPOSITE[a] === b) return { kind: "paired", a, b };
  return { kind: "mismatched", a, b, expected: OPPOSITE[a] };
}

/**
 * 給畫面用的一句話說明。
 *
 * ⚠️ 訊息裡要寫出**原本的名稱**與**期望的方位**，不要只說「不成對」——
 *   使用者要能直接看出該去改哪一個字。
 */
export function directionPairMessage(
  nameA: string,
  nameB: string,
  verdict: DirectionPairVerdict,
): string {
  if (verdict.kind !== "mismatched") return "";
  return (
    `方向名稱「${nameA}」與「${nameB}」不是一條路的兩個方向：` +
    `「${verdict.a}」的相反方向是「${verdict.expected}」，不是「${verdict.b}」。` +
    `常見原因是其中一個打錯字。`
  );
}
